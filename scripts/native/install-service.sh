#!/usr/bin/env bash
# Installs Rakazo as a systemd user service that survives a crash and a logout.
#
#   bash scripts/native/install-service.sh
#
# Stop a manually started stack first (Ctrl+C in the terminal running start.sh), or the service
# will pick another port block because 3100 and 5173 are taken.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
UNIT_DIR="${XDG_CONFIG_HOME:-$HOME/.config}/systemd/user"
UNIT="$UNIT_DIR/rakazo-native.service"
STATE="$HOME/.local/share/rakazo-native"
WRAPPER="$STATE/run-service.sh"

mkdir -p "$UNIT_DIR" "$STATE"
chmod 700 "$STATE" 2>/dev/null || true

# The user manager can carry a display from the login session, and with linger it outlives that
# session. A display that is set but no longer answers makes browser.sh choose headful Chrome on a dead
# screen, and start.sh then fails under set -e, so supervise.sh restarts the whole stack in a loop. The
# generated wrapper below therefore drops a display the moment its socket stops answering.
cat >"$WRAPPER" <<EOF
#!/usr/bin/env bash
# Generated by install-service.sh: hands the stack the graphical session only while it is alive.
set -euo pipefail
if [ -n "\${DISPLAY:-}" ]; then
  case "\$DISPLAY" in
    :*) x_display="\${DISPLAY#*:}"
        # DISPLAY may carry a screen (":0.0"); the socket is named for the display alone ("X0").
        x_display="\${x_display%%.*}"
        x_socket="/tmp/.X11-unix/X\${x_display}"
        if [ ! -S "\$x_socket" ] || [ ! -O "\$x_socket" ]; then
          unset DISPLAY XAUTHORITY
        elif [ -n "\${XAUTHORITY:-}" ] && [ ! -r "\$XAUTHORITY" ]; then
          # A stale XAUTHORITY fails on a live socket; X clients fall back to ~/.Xauthority without it.
          unset XAUTHORITY
        fi ;;
  esac
fi
if [ -n "\${WAYLAND_DISPLAY:-}" ]; then
  if [ -z "\${XDG_RUNTIME_DIR:-}" ] || [ ! -S "\$XDG_RUNTIME_DIR/\$WAYLAND_DISPLAY" ]; then
    unset WAYLAND_DISPLAY
  fi
fi
exec /bin/bash "$ROOT/scripts/native/supervise.sh"
EOF
chmod 700 "$WRAPPER"

cat >"$UNIT" <<EOF
[Unit]
Description=Rakazo native stack (no Docker)
After=network-online.target

[Service]
Type=simple
WorkingDirectory=$ROOT
ExecStart=/bin/bash $WRAPPER
Restart=always
RestartSec=5
KillMode=control-group
TimeoutStopSec=30
Environment=TMPDIR=/dev/shm/rakazo/tmp

[Install]
WantedBy=default.target
EOF

# A display imported into this user manager would stay set after a logout (linger keeps the manager
# alive) while its X or Wayland socket is gone. browser.sh only checks that DISPLAY is non-empty, so it
# would pick headful Chrome on a dead screen and take the whole stack down with it. The generated
# wrapper therefore hands the stack a display only while the socket still answers. Importing here is
# best effort: a manager started after a reboot has no display, and the shared browser then runs
# headless until this script is run again from a desktop session.
systemctl --user import-environment DISPLAY WAYLAND_DISPLAY XAUTHORITY || true
systemctl --user daemon-reload
systemctl --user enable --now rakazo-native.service
systemctl --user --no-pager --lines=0 status rakazo-native.service | head -5

cat <<'TXT'

Rakazo runs as a user service now.

  systemctl --user status rakazo-native     # what it is doing
  journalctl --user -u rakazo-native -f     # live logs
  systemctl --user restart rakazo-native    # restart the stack
  systemctl --user stop rakazo-native       # stop it

To keep it running after you log out (needed for 24/7), run once:

  sudo loginctl enable-linger "$USER"

The unit gets the display of the terminal that ran this script, and the generated wrapper drops it as
soon as its X or Wayland socket stops answering (for example after a logout). While a display is live
the shared browser is headful; otherwise it runs headless, and Google refuses a sign-in there. After a
reboot the user manager has no display, so the stack starts headless: the Google session already in
the profile remains, and a new sign-in needs scripts/native/browser-login.sh run from a desktop
session, which opens a real window and restarts the shared browser headful on the same profile. A
restart of the stack alone keeps the shared browser running while its port answers.

Postgres and the browser stay up across a stack restart. A restart ends runs in progress.
TXT
